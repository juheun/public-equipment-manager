-- -----------------------------------------------------------------------------
-- 1) 대량 생성
-- -----------------------------------------------------------------------------
-- serial_no를 900001번부터 시작해 기존 시드 데이터(최대 450번)와 절대 겹치지
-- 않게 한다 — equipments_serial_no_active_key(활성 장비 범위 유니크 인덱스)에
-- 걸리지 않는다. 제조사/용량/상태를 무작위로 섞어 정렬·필터·무한 스크롤을
-- 다양한 조합으로 눈으로 확인할 수 있게 한다.
--
-- 생성 개수를 바꾸려면 아래 generate_series(1, 500)의 500만 원하는 값으로
-- 바꾸면 된다. PAGE_SIZE=24 기준으로 500개면 약 21페이지 분량의 무한 스크롤을
-- 테스트할 수 있다.
insert into equipments (
  maker, capacity_kva, serial_no, status, current_location, ownership_type, notes
)
select
  maker,
  capacity_kva,
  serial_no,
  status,
  case when status = 'RENTED' then site else '회사' end as current_location,
  'OWNED' as ownership_type,
  '[테스트용 더미 장비] 대량 데이터 성능 테스트 - 테스트 후 삭제 예정' as notes
from (
  select
    n,
    (array['도요', '덴요', '에어맨 구형', '에어맨 신형', 'KW', '구형 발전기'])[1 + floor(random() * 6)::int] as maker,
    (array[25, 60, 150, 300, 400, 500])[1 + floor(random() * 6)::int] as capacity_kva,
    900000 + n as serial_no,
    -- AVAILABLE 비중을 살짝 높여 실제 운영 데이터의 분포(대기 물량이 가장 많음)에 가깝게 한다.
    (array['AVAILABLE', 'AVAILABLE', 'RENTED', 'MAINTENANCE'])[1 + floor(random() * 4)::int] as status,
    (array['미르화학', '청람에너지파크', '새별이엔지 제1공장', '온빛중공업 제1조선소'])[1 + floor(random() * 4)::int] as site
  from generate_series(1, 500) as n
) t;

